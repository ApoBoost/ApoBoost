/** この版の規約に、管理者がもう同意しているか */
export function termsAgreed(): boolean {
  return getSetting(S.termsAgreed, "").split("|")[0] === TERMS_VERSION;
}
/** 同意を記録する（版・日時・同意した人） */
export function agreeTerms(who: string): void {
  const at = new Date(Date.now() + 9 * 3600_000).toISOString().replace("T", " ").slice(0, 16);
  setSetting(S.termsAgreed, `${TERMS_VERSION}|${at}|${who.replace(/\|/g, "")}`);
}
/** 同意した日時と人（画面に出す用） */
export function termsAgreedInfo(): { at: string; who: string } | null {
  const [v, at, who] = getSetting(S.termsAgreed, "").split("|");
  return v === TERMS_VERSION ? { at: at ?? "", who: who ?? "" } : null;
}
